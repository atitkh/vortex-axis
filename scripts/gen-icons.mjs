// Writes the board's copy of the face's icons from web/icons.js, the one definition.
// Run after changing an icon: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ICONS, ICON_DOTS, ICON_HOLE, ICON_PEN, ICON_SIZE, ICON_MS, ICON_TINTS, SHAPE_DOT, SHAPE_DOTS_MIN, SHAPE_HALO, SHAPE_SIZE, iconDots } from "../web/icons.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tenths = (value) => Math.max(0, Math.min(240, Math.round(value * 10)));

const points = [];
const icons = [];
for (const [name, strokes] of Object.entries(ICONS)) {
  icons.push({ name, start: points.length, strokes: strokes.length });
  for (const stroke of strokes) points.push(stroke.length / 2, ...stroke.map(tenths));
}

const dots = Object.keys(ICONS).map((name) => `    {${iconDots(name).map(tenths).join(", ")}},`);
const tints = Object.keys(ICONS).map((name) => `    {${(ICON_TINTS[name] ?? [1, 1, 1]).map((v) => Math.round(v * 255)).join(", ")}},`);

const lines = [];
for (let i = 0; i < points.length; i += 20) lines.push(`    ${points.slice(i, i + 20).join(", ")},`);

writeFileSync(
  join(root, "firmware/waveshare-amoled-1.8/src/icons.h"),
  `#pragma once

// GENERATED by scripts/gen-icons.mjs from web/icons.js. Do not edit: change the icon there and run the script.
//
// The icons the face shows while an agent works (docs/face.md section 8). Each icon is a run of
// strokes in POINTS: a count of points, then that many x, y pairs in tenths of a 24 by 24 grid.

#include <Arduino.h>

namespace icons {

struct Icon {
    const char *name;
    uint16_t start;
    uint8_t strokes;
};

/** Side of the square an icon is drawn in, the width of the pen, and the room the arms leave it, in the face's 240 grid. */
const float SIZE = ${ICON_SIZE};
const float PEN = ${ICON_PEN};
const float HOLE = ${ICON_HOLE};

static const uint8_t POINTS[] = {
${lines.join("\n")}
};

static const Icon ICONS[] = {
${icons.map((icon) => `    {"${icon.name}", ${icon.start}, ${icon.strokes}},`).join("\n")}
};
const int COUNT = sizeof(ICONS) / sizeof(ICONS[0]);

// The same icons made of the face's own dots: where each of its ${ICON_DOTS} dots goes, as x, y pairs in
// tenths of the 24 grid, in the order of ICONS. And the colour each kind leans towards, red, green, blue.
const int DOTS = ${ICON_DOTS};
const float SHAPE_SIZE = ${SHAPE_SIZE};
const float SHAPE_DOT = ${SHAPE_DOT};
/** With fewer dots than all in the shape, the rest turn in a ring this far out. The usual time to form, and the fewest dots a shape may have. */
const float HALO = ${SHAPE_HALO};
const float MS = ${ICON_MS};
const int DOTS_MIN = ${SHAPE_DOTS_MIN};

static const uint8_t SHAPES[][DOTS * 2] = {
${dots.join("\n")}
};

static const uint8_t TINTS[][3] = {
${tints.join("\n")}
};

}  // namespace icons
`,
);
console.log(`wrote ${icons.length} icons, ${points.length} bytes`);
