#!/usr/bin/env python3
"""Generate the compiled-in wake-word model header.

Swapping the built-in model used to mean editing six places by hand - the byte
array, the symbol name in two spots, WW_BUILTIN_NAME, WW_CUTOFF,
WW_WINDOW_DEFAULT - plus a seventh that DUPLICATED the cutoff as the default
wakesns in config.cpp. Nothing stopped those drifting apart, and a cutoff that
disagrees with the model it belongs to is invisible: the wake word simply fires
too often or never.

This emits all of it from one source of truth, so the model and its tuning
cannot disagree.

    tools/gen_builtin_model.py models/hey_mylo.tflite \\
        --json models/hey_mylo.json -o src/model_builtin.h

    tools/gen_builtin_model.py models/hey_mylo.tflite \\
        --name "Hey Mylo" --cutoff 91 --window 5 -o src/model_builtin.h

The manifest is preferred when present; explicit flags override it, and are the
way in when a model was recovered from a device and its .json is long gone.
"""
import argparse
import json
import sys
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tflite", type=Path)
    ap.add_argument("--json", type=Path, help="microWakeWord manifest")
    ap.add_argument("--name", help="display name, e.g. 'Hey Mylo'")
    ap.add_argument("--cutoff", type=int, help="probability cutoff, percent")
    ap.add_argument("--window", type=int, help="sliding window size")
    ap.add_argument("-o", "--out", type=Path, default=Path("src/model_builtin.h"))
    a = ap.parse_args()

    blob = a.tflite.read_bytes()
    # The flatbuffer identifier sits at offset 4. Catching a wrong file here
    # beats discovering it as a model that loads and never fires.
    if blob[4:8] != b"TFL3":
        print(f"error: {a.tflite} is not a TFLite flatbuffer "
              f"(no TFL3 tag at offset 4)", file=sys.stderr)
        return 1

    name, cutoff, window = a.name, a.cutoff, a.window
    if a.json and a.json.exists():
        m = json.loads(a.json.read_text())
        micro = m.get("micro", {})
        name = name or m.get("wake_word")
        if cutoff is None and "probability_cutoff" in micro:
            cutoff = round(float(micro["probability_cutoff"]) * 100)
        window = window or micro.get("sliding_window_size")
        # A manifest cannot change this: it sets the listener's frame size, and
        # the whole capture path is built around 10 ms / 160 samples at 16 kHz.
        step = micro.get("feature_step_size")
        if step not in (None, 10):
            print(f"error: feature_step_size={step}; only 10 ms is supported",
                  file=sys.stderr)
            return 1

    if not name:
        print("error: no --name and no wake_word in the manifest", file=sys.stderr)
        return 1
    if cutoff is None or not (50 <= cutoff <= 99):
        print(f"error: cutoff {cutoff} out of range (50-99)", file=sys.stderr)
        return 1
    window = window or 5
    if not (1 <= window <= 12):
        print(f"error: window {window} out of range (1-12)", file=sys.stderr)
        return 1

    lines = []
    for i in range(0, len(blob), 16):
        chunk = blob[i:i + 16]
        lines.append("    " + " ".join(f"0x{b:02x}," for b in chunk))

    a.out.write_text(
        f"// Generated by tools/gen_builtin_model.py from {a.tflite.name} - do not edit.\n"
        f"// microWakeWord \"{name}\", streaming int8, resource-variable state.\n"
        "#pragma once\n"
        "#include <stdint.h>\n"
        "\n"
        f"#define WW_BUILTIN_NAME       \"{name} (built-in)\"\n"
        f"#define WW_BUILTIN_CUTOFF_PCT {cutoff}\n"
        f"#define WW_BUILTIN_WINDOW     {window}\n"
        f"#define WW_BUILTIN_LEN        {len(blob)}\n"
        "\n"
        # 16-byte alignment: TFLM maps the flatbuffer in place and unaligned
        # access on the S3 is a fault, not a slowdown.
        "alignas(16) const unsigned char ww_builtin_model[] = {\n"
        + "\n".join(lines) +
        "\n};\n"
    )
    print(f"{a.out}: {name}, {len(blob)} bytes, cutoff {cutoff}%, window {window}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
